"""고정 카메라·지그 세팅에서, 보드가 나오는 영역(ROI)을 잘라낸다.

카메라와 촬영 지그가 고정되어 있어서 들어오는 이미지의 해상도·프레임은
항상 같다. 카메라가 눕혀서 찍기 때문에 먼저 왼쪽(반시계) 90도로 돌리고,
그 다음 고정된 사각형(ROI)으로 잘라낸다.

테스트 사진 두 장(부품 없는 것 / 부품 장착된 것)에 같은 회전+크롭 좌표를
적용해봤고, 둘 다 정확히 같은 영역(행 10~30 밴드)이 잘려 나오는 것을
확인함 — 카메라·지그가 고정이라는 전제가 실제로 맞다는 뜻.
(WORKLOG.md 2026-09-22 참고)

(홀 픽셀 위치가 아주 조금씩 달라지는 미세한 부분은 이 크롭과는 별개로
calibration.py가 크롭된 이미지 안에서 따로 보정한다. 이 모듈은 "보드가
있는 영역만 남기고 나머지는 잘라내는" 역할만 한다.)
"""

import cv2
import numpy as np

# 카메라가 눕혀서 찍혀서, 크롭보다 먼저 이 방향으로 돌려야 한다.
ROTATE = cv2.ROTATE_90_COUNTERCLOCKWISE

# (x1, y1, x2, y2) 픽셀 좌표. ROTATE 적용 후 기준, 보드가 있는 영역.
# 테스트 사진(3024x4032 세로 사진 -> 회전 후 4032x3024 가로)으로 잡은 값.
ROI: tuple[int, int, int, int] = (1350, 646, 2630, 1818)


def crop_to_roi(image: np.ndarray) -> np.ndarray:
    """디코딩된 원본 이미지를 회전 후 고정 ROI로 잘라낸다.

    image: cv2로 디코딩한 BGR 배열 (H, W, 3), 회전 전(카메라가 찍은 그대로)
    """
    rotated = cv2.rotate(image, ROTATE)
    x1, y1, x2, y2 = ROI
    return rotated[y1:y2, x1:x2]
