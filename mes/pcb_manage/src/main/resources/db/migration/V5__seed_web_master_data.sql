CREATE TABLE station (
    station_id VARCHAR(50) PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('RUNNING', 'STOP', 'ERROR', 'OFFLINE')),
    product_id VARCHAR(50) REFERENCES product(product_id),
    recipe_id UUID REFERENCES recipe(recipe_id),
    camera_status VARCHAR(20) NOT NULL,
    ai_status VARCHAR(20) NOT NULL,
    mes_status VARCHAR(20) NOT NULL,
    last_seen TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ai_model (
    model_id VARCHAR(50) PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    version VARCHAR(30) NOT NULL,
    framework VARCHAR(50) NOT NULL,
    class_count INTEGER NOT NULL CHECK (class_count >= 0),
    input_size VARCHAR(30) NOT NULL,
    map50 DECIMAL(6, 5),
    map95 DECIMAL(6, 5),
    active BOOLEAN NOT NULL DEFAULT FALSE,
    note VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_ai_model_name_version UNIQUE (name, version)
);

CREATE TABLE ai_model_class (
    model_id VARCHAR(50) NOT NULL REFERENCES ai_model(model_id),
    class_name VARCHAR(100) NOT NULL,
    PRIMARY KEY (model_id, class_name)
);

